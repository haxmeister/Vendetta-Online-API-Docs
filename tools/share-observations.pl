#!/usr/bin/env perl
use v5.36;
use strict;
use warnings;
use FindBin;
use File::Find qw(find);
use File::Path qw(make_path);
use File::Spec;
use Getopt::Long qw(GetOptions);

# Never publish raw captures. They may contain chat, player data or secrets.
# Only shapes/types go into the shareable report.
my $repo = File::Spec->rel2abs(File::Spec->catdir($FindBin::Bin, '..'));
my $default_captures = File::Spec->catdir($repo, 'captures');
my $default_output = File::Spec->catfile($repo, 'docs', 'research', 'capture-summary.md');
my ($captures, $output, $push, $help) =
    ($default_captures, $default_output, 0, 0);
GetOptions(
    'captures=s' => \$captures,
    'output=s'   => \$output,
    'push'       => \$push,
    'help'       => \$help,
) or die "usage: perl tools/share-observations.pl [--captures DIR] [--output FILE] [--push]\n";
if ($help) {
    say 'usage: perl tools/share-observations.pl [--captures DIR] [--output FILE] [--push]';
    exit 0;
}
die "captures directory not found: $captures\n" if !-d $captures;
if ($push && ($captures ne $default_captures || $output ne $default_output)) {
    die "--push only works with the repository's default capture and summary paths\n";
}

my (%observed, %count);
for my $kind (qw(function event)) {
    my $directory = File::Spec->catdir($captures, $kind);
    next if !-d $directory;
    find({ no_chdir => 1, wanted => sub {
        my $path = $File::Find::name;
        return if !-f $path || -l $path;
        return if $path !~ m{[\\/]\Q$kind\E[\\/]([A-Za-z_][A-Za-z0-9_]*)[\\/]([0-9A-Za-z_.-]+\.txt)\z};
        my ($name, $file) = ($1, $2);
        return if -s $path > 65536;
        open my $fh, '<:raw', $path or die "cannot read $path: $!\n";
        my $text = do { local $/; <$fh> };
        close $fh;
        my $signature = $kind eq 'function'
            ? function_signature($text, $name)
            : event_signature($text, $name);
        return if !defined $signature;
        $observed{$kind}{$name}{$signature}++;
        $count{$kind}++;
    }}, $directory);
}

my @lines = (
    '# Local VO API observations — sanitized summary',
    '',
    'Generated by tools/share-observations.pl from local captures.',
    'This report omits returned string contents, numerical values, error messages,',
    'event payloads, chat and notes. It includes function/event names and types only.',
    'Observations are not proof of a universal function or event signature.',
    '',
    '## Functions',
    '',
    '| Function | Observed signature | Samples |',
    '| --- | --- | ---: |',
);
for my $name (sort keys %{ $observed{function} // {} }) {
    for my $signature (sort keys %{ $observed{function}{$name} }) {
        push @lines, '| ' . $name . ' | ' . $signature . ' | '
            . $observed{function}{$name}{$signature} . ' |';
    }
}
if (!$count{function}) { push @lines, '| *No function inspections* | — | 0 |' }
push @lines, ('', '## Events', '',
    '| Event | Observed signature | Samples |',
    '| --- | --- | ---: |');
for my $name (sort keys %{ $observed{event} // {} }) {
    for my $signature (sort keys %{ $observed{event}{$name} }) {
        push @lines, '| ' . $name . ' | ' . $signature . ' | '
            . $observed{event}{$name}{$signature} . ' |';
    }
}
if (!$count{event}) { push @lines, '| *No event captures* | — | 0 |' }
push @lines, ('', '## Coverage', '',
    '- Function inspection records: ' . ($count{function} // 0),
    '- Event observation records: ' . ($count{event} // 0),
    '- Inventory snapshots and other raw captures are excluded.',
    '',
);
my (undef, $dir) = File::Spec->splitpath($output);
make_path($dir) if $dir ne '' && !-d $dir;
open my $out, '>:raw', $output or die "cannot write $output: $!\n";
print {$out} join("\n", @lines);
close $out or die "cannot close $output: $!\n";
say "Wrote $output";
say "Included " . ($count{function} // 0) . " function and "
    . ($count{event} // 0) . " event records (types only).";

if ($push) {
    say '';
    say 'This will COMMIT AND PUSH the sanitized report to your PUBLIC GitHub repository.';
    say 'Raw captures are excluded, but pushing also publishes pending local commits.';
    say "Review $output before approving.";
    print 'Publish to GitHub now? [y/N] ';
    my $answer = <STDIN> // '';
    if ($answer !~ /^y(?:es)?\s*$/i) {
        say 'Not published; report remains local.';
        exit 0;
    }
    run_git('add', '--', 'docs/research/capture-summary.md');
    my $changed = system('git', '-C', $repo, 'diff', '--cached',
        '--quiet', '--', 'docs/research/capture-summary.md');
    die "git diff failed\n" if $changed == -1 || $changed > 256;
    if ($changed == 0) {
        say 'No report changes to commit.';
    } else {
        run_git('commit', '-m', 'Update sanitized VO API observation summary',
            '--', 'docs/research/capture-summary.md');
    }
    run_git('push');
    say 'Report published. Ask ChatGPT to read docs/research/capture-summary.md.';
}

sub run_git (@args) {
    system('git', '-C', $repo, @args) == 0
        or die "git @args failed\n";
}

sub function_signature ($text, $name) {
    return if $text !~ /^format=api-inspect-v1\r?$/m;
    return if $text !~ /^function=\Q$name\E\r?$/m;
    my ($result) = $text =~ /^result=(ok|error)\r?$/m;
    return if !defined $result;
    return 'error (details omitted)' if $result eq 'error';
    my ($returns) = $text =~ /^returns=(\d+)\r?$/m;
    return if !defined $returns || $returns > 10000;
    my %types;
    while ($text =~ /^return(\d+) type=(nil|boolean|number|string|table|userdata|thread|function)(?:[ \t].*)?\r?$/mg) {
        $types{$1} = $2 if $1 <= 24;
    }
    my @ordered;
    for my $i (1 .. ($returns < 24 ? $returns : 24)) {
        push @ordered, $types{$i} // '?';
    }
    push @ordered, '…' if $returns > 24;
    return 'ok: ' . $returns . ' returns (' . join(', ', @ordered) . ')';
}

sub event_signature ($text, $name) {
    return if $text !~ /^event=\Q$name\E\r?$/m;
    my ($n) = $text =~ /^arguments=(\d+)\r?$/m;
    return if !defined $n || $n > 10000;
    my %types;
    while ($text =~ /^arg(\d+) type=(nil|boolean|number|string|table|userdata|thread|function)(?:[ \t].*)?\r?$/mg) {
        $types{$1} = $2 if $1 <= 16;
    }
    my @ordered;
    for my $i (1 .. ($n < 16 ? $n : 16)) {
        push @ordered, $types{$i} // '?';
    }
    push @ordered, '…' if $n > 16;
    return $n . ' args (' . join(', ', @ordered) . ')';
}
