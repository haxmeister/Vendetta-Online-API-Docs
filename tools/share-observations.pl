#!/usr/bin/env perl
use v5.36;
use strict;
use warnings;
use FindBin;
use File::Find qw(find);
use File::Path qw(make_path);
use File::Spec;
use Getopt::Long qw(GetOptions);

# Preserve chat table keys and nested types for API research, but omit
# conversational chat strings and chat table example values from public reports.
# Bounded full values are retained in local captures only.
# Publishing is opt-in because the destination repository is public.
my $repo = File::Spec->rel2abs(File::Spec->catdir($FindBin::Bin, '..'));
my $default_captures = File::Spec->catdir($repo, 'captures');
my $default_output = File::Spec->catfile($repo, 'docs', 'research', 'capture-summary.md');
my $reviewed_file = File::Spec->catfile($repo, 'data', 'reviewed-through.txt');
my ($captures, $output, $push, $help, $all) =
    ($default_captures, $default_output, 0, 0, 0);
GetOptions(
    'captures=s' => \$captures,
    'output=s'   => \$output,
    'reviewed-file=s' => \$reviewed_file,
    'push'       => \$push,
    'all'        => \$all,
    'help'       => \$help,
) or die "usage: perl tools/share-observations.pl [--captures DIR] [--output FILE] [--reviewed-file FILE] [--all] [--push]\n";
if ($help) {
    say 'usage: perl tools/share-observations.pl [--captures DIR] [--output FILE] [--reviewed-file FILE] [--all] [--push]';
    exit 0;
}
die "captures directory not found: $captures\n" if !-d $captures;
if ($push && ($captures ne $default_captures || $output ne $default_output)) {
    die "--push only works with the repository's default capture and report paths\n";
}

# The maintainer advances this marker only after consolidating observations
# into the permanent reference. Raw files remain in captures/ locally.
my $reviewed_through;
if (!$all && $captures eq $default_captures && -f $reviewed_file) {
    open my $prior, '<', $reviewed_file or die "cannot read $reviewed_file: $!\n";
    while (my $line = <$prior>) {
        chomp $line;
        $line =~ s/#.*\z//;  # whole-line and inline comments
        $line =~ s/\A\s+|\s+\z//g;  # blanks, including CRLF
        next if $line eq '';
        die "invalid reviewed-through timestamp: $line\n"
            unless $line =~ /\A\d{8}T\d{6}\.\d{6}Z\z/;
        $reviewed_through = $line;
    }
    close $prior;
}

my (@captures, %count);
for my $kind (qw(function event snapshot note)) {
    my $directory = File::Spec->catdir($captures, $kind);
    next if !-d $directory;
    find({ no_chdir => 1, wanted => sub {
        my $path = $File::Find::name;
        return if !-f $path || -l $path;
        my $relative = File::Spec->abs2rel($path, $directory);
        return if $relative !~ m{\A([A-Za-z_][A-Za-z0-9_.-]*)/([A-Za-z0-9_.-]+\.txt)\z};
        my ($name, $file) = ($1, $2);
        my ($timestamp) = $file =~ /\A(\d{8}T\d{6}\.\d{6}Z)-/;
        return if defined $reviewed_through && defined $timestamp
            && $timestamp le $reviewed_through;
        die "capture is too large for report: $path\n" if -s $path > 262144;
        open my $fh, '<:raw', $path or die "cannot read $path: $!\n";
        my $body = do { local $/; <$fh> };
        close $fh;
        my ($safe_body, $chat_samples) = sanitize_chat_report($body, $kind, $name);
        push @captures, {
            category => $kind, name => $name, file => $file,
            body => $safe_body, chat_samples => $chat_samples,
        };
        $count{$kind}++;
        $count{chat_sanitized} += $chat_samples;
    }}, $directory);
}

if (!@captures) {
    say "No unreviewed captures found."
        . (defined $reviewed_through ? " (reviewed through $reviewed_through)" : "");
    exit 0;
}

my %order = (function => 0, event => 1, snapshot => 2, note => 3);
@captures = sort {
    $order{$a->{category}} <=> $order{$b->{category}}
    || $a->{name} cmp $b->{name}
    || $a->{file} cmp $b->{file}
} @captures;

my @lines = (
    '# VO API observations — chat schemas preserved',
    '',
    'Generated by tools/share-observations.pl from local captures.',
    (defined $reviewed_through
        ? ('Includes only observations after ' . $reviewed_through . ' UTC.')
        : ('Includes all available local capture records.')),
    'Preserves recorded function values, string contents when available,',
    'errors, event arguments, inventory snapshots, and notes.',
    'For chat events, observed table keys, nesting and field types are kept.',
    'Numeric and boolean arguments are kept; private chat message strings',
    'and representative chat table values remain in local captures only.',
    '**Review this report before publishing to a public repository.**',
    'Other captures may contain character names, locations, or private data.',
    'These observations do not establish universal API signatures.',
    '',
    '## Coverage',
    '',
    '- Function records: ' . ($count{function} // 0),
    '- Event records: ' . ($count{event} // 0),
    '- Snapshots: ' . ($count{snapshot} // 0),
    '- Notes: ' . ($count{note} // 0),
    '- Chat event samples sanitized for public sharing: ' . ($count{chat_sanitized} // 0),
    '',
);
my %headings = (
    function => 'Functions', event => 'Events',
    snapshot => 'Snapshots', note => 'Notes',
);
my $previous = '';
for my $record (@captures) {
    my $kind = $record->{category};
    if ($kind ne $previous) {
        push @lines, "## $headings{$kind}", '';
        $previous = $kind;
    }
    push @lines, '### ' . $record->{name} . ' — ' . $record->{file}, '';
    my $body = $record->{body};
    # Prevent control bytes from affecting the report while retaining all
    # otherwise printable content, including UTF-8 and original line breaks.
    $body =~ s/([\x00-\x08\x0B\x0C\x0E-\x1F\x7F])/sprintf('\\x%02X', ord($1))/ge;
    my @body_lines = split /\n/, $body, -1;
    pop @body_lines if @body_lines && $body_lines[-1] eq '';
    push @lines, map { '    ' . $_ } @body_lines;
    push @lines, '';
}
push @lines, 'No matching captures were found.', '' if !@captures;

my (undef, $dir) = File::Spec->splitpath($output);
make_path($dir) if $dir ne '' && !-d $dir;
open my $out, '>:raw', $output or die "cannot write $output: $!\n";
print {$out} join("\n", @lines), "\n";
close $out or die "cannot close $output: $!\n";
say "Wrote $output";
say 'Included ' . scalar(@captures) . ' captures; preserved chat schemas and sanitized '
    . ($count{chat_sanitized} // 0) . ' chat event samples.';

if ($push) {
    say '';
    say 'This will COMMIT AND PUSH the report to your PUBLIC GitHub repository.';
    say 'Chat table keys/types are included; chat text values are excluded.';
    say 'Non-chat observations may include names, locations, values and errors.';
    say 'Pushing may also publish other local commits.';
    say "Review $output before approving.";
    print 'Publish to GitHub now? [y/N] ';
    my $answer = <STDIN> // '';
    if ($answer !~ /^y(?:es)?\s*$/i) {
        say 'Not published; report remains local.';
        exit 0;
    }
    run_git('add', '--', 'docs/research/capture-summary.md');
    my $changed = system('git', '-C', $repo, 'diff', '--cached',
        '--quiet', '--', 'docs/research/capture-summary.md');
    die "git diff failed\n" if $changed == -1 || $changed > 256;
    if ($changed == 0) {
        say 'No report changes to commit.';
    } else {
        run_git('commit', '-m', 'Update VO API observations (chat schemas; private text omitted)',
            '--', 'docs/research/capture-summary.md');
    }
    # A remote change since the last pull must not cause an avoidable
    # non-fast-forward rejection. Never force-push.
    run_git('pull', '--rebase');
    run_git('push');
    say 'Report published. Ask ChatGPT to review the new observations.';
}

sub run_git (@args) {
    system('git', '-C', $repo, @args) == 0 or die "git @args failed\n";
}

sub chat_event ($name) {
    # Include text entered into chat and slash commands as chat data.
    return $name =~ /\A(?:CHAT_|ACTIVATE_CHAT_|EMOTE_ENTERED\z|COMMAND\z)/;
}

sub sanitize_chat_report ($body, $category, $name) {
    # The collector records full bounded examples locally.
    # Public reports retain nested key names and value types from shape=
    # and argN schema= but never include the example string/table contents.
    my $chat = $category eq 'event' && chat_event($name);
    my $count = $chat ? 1 : 0;
    my @lines = split /\n/, $body, -1;
    for my $line (@lines) {
        if ($category eq 'snapshot') {
            if ($line =~ /^event=([A-Za-z_][A-Za-z0-9_]*)\r?$/) {
                $chat = chat_event($1) ? 1 : 0;
                $count++ if $chat;
            } elsif ($line =~ /^---\r?$/) {
                $chat = 0;
            }
        }
        next if !$chat;
        # Numbers and booleans remain useful for argument discovery.
        if ($line =~ /^(arg\d+ type=(?:string|table|userdata|thread|function))(?: value=.*)?\r?$/) {
            $line = $1;
        }
    }
    return (join("\n", @lines), $count);
}
