#!/usr/bin/env perl
use v5.36;
use strict;
use warnings;
use FindBin;
use File::Spec;

my $repository = File::Spec->catdir($FindBin::Bin, '..');
my $input = $ARGV[0] // File::Spec->catfile($repository, 'data', 'function-candidates.txt');
my $output = $ARGV[1] // File::Spec->catfile($repository, 'plugin', 'APIProbe', 'candidates.lua');

open my $in, '<', $input or die "cannot open $input: $!\n";
my %candidate;
my $line_number = 0;
while (my $line = <$in>) {
    $line_number++;
    $line =~ s/\r?\n\z//;
    $line =~ s/\s*#.*\z//;
    $line =~ s/\A\s+|\s+\z//g;
    next if $line eq '';
    die "$input:$line_number: invalid Lua global identifier: $line\n"
        if $line !~ /\A[A-Za-z_][A-Za-z0-9_]*\z/;
    $candidate{$line} = 1;
}
close $in;
my @names = sort keys %candidate;
die "no candidate names in $input\n" if !@names;

open my $out, '>', $output or die "cannot write $output: $!\n";
print {$out} "-- Generated by tools/build-probes.pl. DO NOT EDIT.\n";
print {$out} "-- Only read candidate values; never invoke the functions.\n";
print {$out} "-- Protected reads handle VO's strict undeclared-global checks.\n";
print {$out} "return {\n";
for my $name (@names) {
    printf {$out} '    {"%s", function() return %s end},' . "\n", $name, $name;
}
print {$out} "}\n";
close $out or die "cannot finish $output: $!\n";
say "Generated " . scalar(@names) . " guarded candidates in $output";
